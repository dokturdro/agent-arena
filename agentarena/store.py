"""Run directory layout:

runs/<run_id>/
  manifest.json      config snapshot, config hash, git sha, versions
  samples.jsonl      one SampleRecord per line (append-only, resumable)
  judgments.jsonl    optional LLM-judge results
  report.html        generated by `arena report` (loads report-data.js next to it)
  report-data.js
"""

from __future__ import annotations

import hashlib
import json
import platform
import subprocess
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from agentarena import __version__
from agentarena.schemas import SampleRecord


def config_hash(obj: Any) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True, default=str).encode()).hexdigest()[:12]


def _git_sha() -> str | None:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


class RunStore:
    def __init__(self, run_dir: Path):
        self.dir = run_dir
        self.samples = run_dir / "samples.jsonl"
        self.judgments = run_dir / "judgments.jsonl"
        self.manifest_path = run_dir / "manifest.json"

    def init(self, suite: dict[str, Any], models: list[dict[str, Any]]) -> dict[str, Any]:
        self.dir.mkdir(parents=True, exist_ok=True)
        cfg = {"suite": suite, "models": models}
        if self.manifest_path.exists():
            manifest = json.loads(self.manifest_path.read_text(encoding="utf-8"))
            if manifest["config_hash"] != config_hash(cfg):
                manifest.setdefault("resumed_with", []).append(config_hash(cfg))
        else:
            manifest = {
                "run_id": self.dir.name,
                "created": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                "config_hash": config_hash(cfg),
                "git_sha": _git_sha(),
                "agentarena": __version__,
                "python": platform.python_version(),
                **cfg,
            }
        self.manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        return manifest

    def manifest(self) -> dict[str, Any]:
        return json.loads(self.manifest_path.read_text(encoding="utf-8"))

    def repair(self) -> None:
        """Drop a torn final line left by an interrupted run so appends start on a clean line."""
        if self.samples.exists():
            recs = self.load()
            self.samples.write_text("".join(r.model_dump_json() + "\n" for r in recs), encoding="utf-8")

    def done_ids(self) -> set[str]:
        """Samples that need no re-run. Infrastructure errors (quota, auth, outages) are retried."""
        return {r.sample_id for r in self.load() if r.trajectory.stop_reason != "error"}

    def append(self, rec: SampleRecord) -> None:
        with self.samples.open("a", encoding="utf-8") as f:
            f.write(rec.model_dump_json() + "\n")

    def load(self) -> list[SampleRecord]:
        if not self.samples.exists():
            return []
        lines = [x for x in self.samples.read_text(encoding="utf-8").splitlines() if x.strip()]
        latest: dict[str, SampleRecord] = {}  # a retried sample supersedes its earlier attempt
        for i, line in enumerate(lines):
            try:
                rec = SampleRecord.model_validate_json(line)
            except ValueError:
                if i == len(lines) - 1:
                    continue  # a torn final line from an interrupted run; it will be re-run
                raise
            latest.pop(rec.sample_id, None)
            latest[rec.sample_id] = rec
        return list(latest.values())

    def load_judgments(self) -> list[dict[str, Any]]:
        if not self.judgments.exists():
            return []
        return [json.loads(x) for x in self.judgments.read_text(encoding="utf-8").splitlines() if x.strip()]

    def append_judgment(self, j: dict[str, Any]) -> None:
        with self.judgments.open("a", encoding="utf-8") as f:
            f.write(json.dumps(j) + "\n")
